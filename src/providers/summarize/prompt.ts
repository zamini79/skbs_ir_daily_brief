/**
 * 담당자에게 제시할 요약 관점. **2안이다 (2026-08-28 확정, 3안에서 줄였다).**
 *
 * 뺀 것은 ③ 시사점 중심이다. 근거는 원본 샘플 엑셀 — 실제로 나가는 요약문은
 * 전부 사실·수치 중심이고 해석이 없다("IDT 바이오로지카 인수 통한 글로벌 공급망
 * 사업자 영역 확장 전략…지난해 연결 매출 6,513억원 달성, 전년 대비 두 배 넘는 성장").
 * 반면 모델이 만든 3안은 "기업 가치 재평가의 핵심 모멘텀이 될 것으로 기대됨" 같은
 * 문장이었다. **전 임원에게 나가는 문서에서 모델이 지어낸 전망이 가장 위험하다.**
 * 담당자가 걸러낼 수는 있지만 애초에 만들지 않는 편이 낫다.
 *
 * **이 판단은 되돌리기 쉽다.** 관점 정의와 프롬프트가 여기 상수로 모여 있으니,
 * 담당자 인터뷰 후 조정 가능하다(스펙 §8.2). 되돌린다면 함께 바뀌어야 하는 곳:
 * `gemini.ts` 의 `responseSchema`·`SummarySet`, 그리고 화면의 `SUMMARY_LABEL`.
 * 발췌 폴백(`buildFallbackSummaries`)은 이 배열의 길이를 따라가므로 손댈 필요 없다.
 */
export const SUMMARY_VARIANTS = [
  { key: 'numeric', variant: 1, label: '수치 중심' },
  { key: 'context', variant: 2, label: '배경·맥락 중심' },
] as const

/** 화면에서 관점 앞에 붙는 번호. 배열 순서가 곧 variant 1, 2, ... 다. */
const CIRCLED_NUMERAL = ['①', '②', '③', '④', '⑤'] as const

/**
 * 저장된 variant 번호를 화면 라벨로 바꾼다. `SUMMARY_VARIANTS` 에서 파생되므로
 * 관점을 늘리거나 줄일 때 라벨이 따로 놀지 않는다.
 *
 * **`SUMMARY_VARIANTS` 에 없는 variant 도 깨지지 않는다.** 이미 저장된 데이터에
 * `variant = 3` 행이 남아 있다 — 3안(시사점 중심)을 뺀 것은 앞으로 생성하지
 * 않는다는 뜻이지 지난 실행의 요약이 사라진다는 뜻이 아니다(재수집하면 사라지지만
 * 그 전에 화면을 열면 그대로 보인다). 라벨 맵을 그대로 인덱싱하면 `undefined` 가
 * 나와 라벨 자리가 **소리 없이 비고**, 담당자는 그 요약이 어느 관점인지도 왜 다른
 * 것과 달라 보이는지도 알 수 없다.
 *
 * 그렇다고 「③ 시사점 중심」으로 되살려 적지는 않는다 — 그 관점을 뺀 이유가
 * "모델이 지어낸 전망이 전 임원용 문서에서 가장 위험하다"이므로, 라벨로 되살리면
 * 없앤 것을 화면에서 정상 선택지처럼 복원하는 셈이다. 대신 **지금은 만들지 않는
 * 것**이라고 사실대로 말한다.
 */
export function summaryVariantLabel(variant: number): string {
  const found = SUMMARY_VARIANTS.find(v => v.variant === variant)
  if (!found) return `${variant}안 (지금은 만들지 않는 관점)`
  return `${CIRCLED_NUMERAL[variant - 1] ?? variant} ${found.label}`
}

export const MAX_SUMMARY_CHARS = 100

/**
 * ## 문체: 명사형 종결 (2026-09-02 사용자 요청으로 변경)
 *
 * 그 전에는 개조식(`~함`, `~임`)이었다. 바뀐 규칙은 **문장을 명사로 끝내는 것**이다:
 * 「급여 확대됨」이 아니라 「급여 확대」, 「심포지엄 계획함」이 아니라 「심포지엄 계획」.
 *
 * **지시만 두지 않고 예시를 함께 둔다.** 「명사로 끝내라」는 추상적이라 모델마다
 * 다르게 읽는다 — 사용자가 준 두 예시가 규칙을 한 번에 확정한다.
 *
 * 실측(2026-09-02, 실제 기사 5건 × 2안 = 10건, 프로덕션과 같은 경로):
 * **모든 문장이 명사로 끝났다.** 문장 끝을 그대로 옮기면 마감 · 하락 · 기록 · 전환 ·
 * 실패 · 완료 · 진행 · 착수 · 체결 · 성사 · 확대 · 지속 · 추진 · 도입 · 제공 ·
 * 목적 · 도모. 서술어로 끝난 문장은 하나도 없었다.
 *
 * **옛 지시를 함께 남기지 마라.** 두 문체를 동시에 요구하면 그날 무엇이 나올지는
 * 모델과 운에 달리고, 화면에 두 문체가 섞인다. `prompt.test.ts` 가 옛 줄이 되살아나는
 * 것을 막는다.
 *
 * 발췌 폴백(`buildFallbackSummaries`)은 기사 본문을 그대로 잘라 쓰므로 이 규칙을
 * 따르지 않는다. 그건 결함이 아니라 폴백의 성질이다 — 모델이 못 만든 자리에 원문
 * 조각을 넣는 것이고, 화면의 「본문 발췌」 배지가 그 사실을 밝힌다. (문장부호·금액
 * 표기는 다르다 — 아래 참고. 그건 코드가 바꿀 수 있고, 발췌에도 입힌다.)
 *
 * ## 문장부호·금액 표기·제목 중복 (2026-10-02 담당자 피드백)
 *
 * 담당자는 화면의 요약을 그대로 임원 메일에 붙인다. 요구한 모양: 문장 사이는 `, `,
 * `…` 은 한 번, 끝 마침표 없음, 금액은 `1,000억원`. 그리고 **제목과 겹치지 않게** —
 * 「셀트리온, 1,000억원 규모 자사주 추가 매입…올해 누적 4,000억원」 기사에서
 * 요약 앞부분이 「1,000억원 규모(56만853주) 자사주 추가 매입 결정, 올해 누적 매입액은
 * 총 4,000억원 달성」이라 제목의 반복이라고 지적받았다.
 *
 * **문장부호·금액은 여기서 요구하되 보장은 `formatSummary` 가 한다**(`enforceLimit`).
 * 모델은 서식을 매번 지키지 않는다. 프롬프트에 적는 이유는 모델이 처음부터 그 모양으로
 * 쓰면 코드가 고칠 일이 줄고, 특히 `…` 위치(화제가 바뀌는 곳)는 코드가 알 수 없어서다.
 *
 * **제목 중복은 코드가 고칠 수 없다** — 무엇이 본문의 주요 내용인지는 모델만 판단한다.
 * 그래서 이 규칙만은 프롬프트가 전부다. 1안(수치 중심)이 특히 위험하다: 제목에 수치가
 * 있으면 그 수치가 곧 "핵심 수치"로 보이기 때문에 명시적으로 막는다.
 *
 * **금액 콤마 규칙은 금액에만이라고 못박는다.** 실측(2026-10-02 첫 측정): 「금액은
 * 천 단위 콤마」만 적었더니 한미약품 기사 본문의 「360만4000여주」를 모델이
 * 「3,600,000여주」로 옮겼다 — 수량에 콤마를 번진 것에 더해 **3,604,000 이 3,600,000
 * 으로 뭉개졌다.** 코드(`formatSummary`)는 원문 숫자를 모르므로 이것을 되돌릴 수 없다.
 *
 * **예시는 「제목 + 제목과 겹치지 않는 좋은 예」 한 쌍이다** (2026-10-02 컨트롤러 판단).
 * 첫 판에서는 담당자 예시 문장을 그대로 싣고 「형식만 참고」라고 붙였다. 그런데 그
 * 문장은 **제목을 반복했다고 지적받은 바로 그 문장**이고, 예시는 모델이 가장 강하게
 * 따라 하는 신호다. 게다가 제목을 함께 싣지 않아서 모델은 그 예시가 제목과 겹친다는
 * 사실조차 알 수 없었다 — 「형식만 참고」는 모델이 확인할 수 없는 주의문이었다.
 *
 * 그래서 제목을 함께 싣고, 같은 문장부호 형식으로 **제목에 없는 사실만** 쓴 요약을
 * 좋은 예로 둔다. 쓴 사실(56만853주, 당기순이익의 33% 주주환원)은 담당자 예시에 나온
 * 것 중 제목에 없는 것뿐이다 — 예시라도 지어낸 사실을 넣지 않는다.
 * 담당자 원문은 「나쁜 예」로도 싣지 않는다. 나쁜 예 역시 따라 할 신호가 된다.
 *
 * 좋은 예는 두 화제를 `…` 로 잇는다(2라운드). 첫 판의 좋은 예 「취득 주식은 56만853주
 * 규모, …」는 `…` 를 보여 주지 않아 그 규칙이 지시문에만 남았고, 「~는 N 규모,」
 * 문형을 모델이 복제했다 — 실측 3차에서 「참석자는 160여명 규모,」(제목의 수치)가 나왔다.
 * 옛 「기사 제목을 반복하지 말 것」은 지웠다 — 새 규칙과 나란히 두면 같은 말을 두
 * 번 하는 정도가 아니라, 짧은 쪽이 「문장 그대로 베끼지만 말라」로 읽힐 여지가 있다.
 */

export function buildPrompt(title: string, body: string): string {
  return `다음 기사를 IR 데일리 브리프용으로 요약한다. 서로 다른 관점의 요약 2안을 작성하라.

1안(수치 중심): 기사의 핵심 수치를 중심으로
2안(배경·맥락 중심): 왜 이런 일이 일어났는지 배경을 중심으로

제약:
- 각 요약은 공백 포함 ${MAX_SUMMARY_CHARS}자 이내. 반드시 지킬 것.
- **모든 문장을 명사로 끝낼 것.** 서술어로 끝내지 말고 명사형으로 바꾼다.
  - "급여 확대됨" → "급여 확대"
  - "심포지엄 계획함" → "심포지엄 계획"
  - "2,629억원 규모 계약 체결함" → "2,629억원 규모 계약 체결"
  - "전년 대비 두 배 넘게 성장했다" → "전년 대비 두 배 넘는 성장"
- **제목에 이미 나온 사실은 다시 쓰지 말 것.** 제목에 없는 본문의 주요 내용을 담는다.
  1안(수치 중심)도 마찬가지다 — 제목에 이미 있는 수치 대신 본문에만 있는 수치를 쓴다.
- 문장 사이는 쉼표와 공백(", ")으로 잇는다. 화제가 바뀌는 곳 한 곳에만 말줄임표(…)를 쓴다. 마침표는 쓰지 않는다(맨 끝 포함).
- 원화 금액은 천 단위 콤마와 "원"을 붙인다: "1000억" → "1,000억원", "4000억원" → "4,000억원".
  이 규칙은 금액에만 적용한다. 주식 수·인원 등 수량과 연도는 기사 표기 그대로 쓴다("360만4000여주", "56만853주", "2026년").

예시 — 제목에 이미 있는 금액(1,000억원, 누적 4,000억원)과 자사주 매입 사실은 쓰지 않고, 본문에만 있는 내용으로 요약한다:
- 제목: 셀트리온, 1,000억원 규모 자사주 추가 매입…올해 누적 4,000억원
- 좋은 요약: 취득 주식은 56만853주…중장기적으로 당기순이익의 33%를 주주에게 환원할 방침

제목: ${title}

기사:
${body}`
}
