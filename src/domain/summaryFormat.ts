import { truncateAtClause } from './text'

/**
 * ## 화면에 나가는 요약의 모양 (담당자 피드백 2026-10-02)
 *
 * 검수 담당자는 화면의 요약을 **그대로 복사해 임원 메일에 붙인다.** 그래서 요약은
 * 메일에 나갈 모양 그대로 만들어져야 한다:
 *
 *   셀트리온이 1,000억원 규모(56만853주) 자사주 추가 매입 결정, 올해 누적 매입액은
 *   총 4,000억원 달성…중장기적으로 당기순이익의 33%를 주주에게 환원할 방침
 *
 * - 문장 사이는 `, ` 로 잇고 `…` 은 한 번만. 끝에 마침표가 없다.
 * - 원화 금액은 천 단위 콤마와 `원`.
 *
 * **프롬프트에도 같은 규칙을 적었지만 그것만 믿지 않는다.** 모델은 문장부호·숫자
 * 서식을 매번 지키지 않고, 발췌 폴백은 기사 원문 그대로라 애초에 이 모양이 아니다.
 * 화면에 나가는 모양은 이 함수가 보장한다 — 출처(모델/발췌)와 무관하게.
 *
 * 이 함수는 **문장부호와 숫자 표기만** 바꾼다. 단어를 더하거나 빼지 않는다(예외는
 * `[조억]` 뒤의 `원` 보충 하나 — 아래 `addWon`).
 */
export function formatSummary(text: string): string {
  let s = text.trim()
  if (!s) return ''

  // 줄바꿈도 문장 경계다. 모델이 2문장을 두 줄로 내는 경우가 있다.
  s = s.replace(/\s*[\r\n]+\s*/g, '. ')
  s = s.replace(/[ \t]+/g, ' ')

  // 1. 말줄임표 통일. 예시 문장처럼 앞뒤 공백 없이 붙인다(`달성…중장기적으로`).
  s = s.replace(/\.{3,}|‥/g, '…')
  s = s.replace(/\s*…+\s*/g, '…')

  // 2. 문장 경계 마침표 → `, `. **경계로 보는 `.` 를 좁게 정의한다** — 「앞뒤가 숫자가
  //    아니면 경계」로 했더니 영문 약어가 부서졌다(리뷰 2026-10-02: `No.1` → `No, 1`,
  //    `U.S. 시장` → `U, S, 시장`, `Co., Ltd.` → `Co, Ltd`). 경계는:
  //    - 앞이 한글·`%`·닫는 따옴표/괄호·`,` 이고 뒤가 공백·끝·한글·숫자 (`증가. 다음`,
  //      `30%. 다음`, `다.2분기`, 모델이 흘린 `결정,. 다음`)
  //    - 앞이 숫자이고 뒤가 공백·끝·한글 (`4,000. 다음`). 뒤도 숫자면 소수점(`4.4조`).
  //    (뒤가 `,`·`…` 인 것도 경계다 — 모델이 흘린 `결정.…다음`. 정리 단계가 합친다.)
  //    앞이 영문이면 경계가 아니다 — 약어다. 대가로 `IPO. 다음` 같은 영문 끝 문장은
  //    마침표가 남는다(맨 끝이면 아래 정리 단계가 지운다).
  //    `。` 는 언제나 경계다. 마침표가 닫는 따옴표 안에 있으면(`증가.” 다음`) 밖으로
  //    꺼낸 뒤 판단한다 — 안 꺼내면 `증가, ” 다음` 이 된다.
  s = s.replace(/\.((?:["”’'」』)\]])+)/g, '$1.')
  s = s.replace(
    /\s*(?:(?<=[가-힣%,"”’'」』)\]])\.(?=\s|$|[가-힣0-9,…])|(?<=[0-9])\.(?=\s|$|[가-힣,…])|。)\s*/g,
    ', ',
  )

  // 3. `…` 은 첫 번째만. 나머지는 `, `.
  let seen = false
  s = s.replace(/…/g, () => {
    if (seen) return ', '
    seen = true
    return '…'
  })

  // 6 → 5 순서: `4000억 규모` 에 `원` 을 먼저 붙여야 금액 콤마 규칙에 걸린다.
  s = addWon(s)
  s = addThousandsSeparators(s)

  // 4. 정리. 구분자가 이어지면 하나로, `…` 옆의 콤마는 `…` 에 흡수.
  s = s.replace(/\s*,(?:\s*,)+/g, ',')
  s = s.replace(/,\s*…|…\s*,\s*/g, '…')
  s = s.replace(/,(?=\S)(?<![0-9],)/g, ', ') // 경계 콤마 뒤 공백 (`1,000` 은 건드리지 않음)
  s = s.replace(/^[\s,…]+/, '')
  s = s.replace(/[\s,….。]+$/, '')
  return s
}

/**
 * 서식 → 절삭. **이 순서여야 한다** — 금액 콤마가 글자 수를 늘리므로, 절삭 뒤에
 * 서식을 입히면 100자를 넘을 수 있다. 화면에 나가는 요약은 전부 이 함수를 지난다
 * (`enforceLimit`, `buildFallbackSummaries`).
 */
export function finalizeSummary(text: string, max: number): string {
  return truncateAtClause(formatSummary(text), max)
}

const CURRENCY = '(?:원|달러|유로|엔|위안|파운드|프랑)'
/** 이 단위가 뒤에 오면 돈이 아니라 수량이다 — `원` 을 붙이지 않는다(`addWon`). */
const COUNTER = '(?:명|주|건|회분|회|개|대|장|톤|배|가구|권|마리|병|부|표|곳|종|채|평|도즈|바이알|뷰)'

/**
 * 5. 금액 천 단위 콤마: `1000억원` → `1,000억원`, `1조2000억원` → `1조2,000억원`.
 *
 * **통화 단어가 뒤에 올 때만** 끊는다. 숫자만 보고 끊으면 연도(`2026년`),
 * 수량(`1200명`, `56만853주`), 코드(`A1234`)까지 바뀐다.
 * - 앞이 숫자·`.`·`,`·영문이면 시작점이 아니다 — 소수의 일부(`0.12345억원`),
 *   이미 콤마가 있는 수(`12,3456억원` 같은 이상한 입력도 그대로 둔다), 코드.
 * - 어림 접미사 `여` 를 허용한다(`1000억여원` → `1,000억여원`).
 * - **통화 앞 공백은 `[조억만천]` 단위가 있을 때만** 허용한다(`4000억 달러`). 숫자 바로
 *   뒤 공백까지 허용했더니 연도가 금액이 됐다(리뷰 2026-10-02: `2026 프랑스` →
 *   `2,026 프랑스`, `2026 원년`, `2025 원가`). 단위 없는 금액은 붙여 쓴다(`1500원`).
 */
function addThousandsSeparators(s: string): string {
  const re = new RegExp(
    `(?<![0-9A-Za-z.,])([0-9]{4,})(?=[조억만천]여?\\s?${CURRENCY}|여?${CURRENCY})`,
    'g',
  )
  return s.replace(re, digits => digits.replace(/\B(?=(?:[0-9]{3})+$)/g, ','))
}

/**
 * 6. `[조억]` 로 끝나는 금액 뒤에 통화가 없으면 `원` 을 붙인다:
 * `4000억 규모` → `4000억원 규모`(콤마는 5가 붙인다), `4.4조 계약` → `4.4조원 계약`,
 * `5천억 규모` → `5천억원 규모`(`천` 표기 — 안 붙이면 메일에 「5천억」과 「4,000억원」이
 * 섞여 나간다).
 *
 * **오탐이 나는 규칙이라 붙이지 않는 쪽으로 넉넉히 비켜 간다.** 붙이지 않으면
 * 「4,000억 규모」로 남을 뿐이지만, 잘못 붙이면 「1억원 명」처럼 메일에 틀린 말이
 * 나간다. 붙이지 않는 경우:
 * - 뒤에 숫자가 이어진다(`1조2000억원`, `1조 2000억원`의 `조`).
 * - 뒤에 이미 통화가 있다(`4000억 달러`).
 * - 뒤가 어림 접미사 `여` 다(`1000억여원`, `1조여원`). 안 막으면 `1조원여원` 이 된다
 *   (리뷰 2026-10-02). 통화 없이 `여` 로 끝나는 `1조여 규모` 도 붙이지 않는다 — 넣을
 *   자리가 `여` 뒤인데, 그 판단까지 규칙에 넣을 만큼 흔하지 않다.
 * - 뒤가 수량 단위다(`1억 명`, `3억 주`, `1억 건`, `1억 도즈`) — 돈이 아니다.
 *   `100억대` 의 `대` 는 금액 범위지만 `100억원대` 로 고치는 것은 이 규칙의 일이
 *   아니어서 그대로 둔다.
 * - 뒤가 영문이다(`1억 USD`, `1조 KRW`).
 * - `제2조` — 조항 번호다.
 * - 앞이 숫자가 아니다(`기억`, `추억`, `조정`).
 */
function addWon(s: string): string {
  const re = new RegExp(
    `(?<![0-9A-Za-z.,제])([0-9][0-9,]*(?:\\.[0-9]+)?천?[조억])(?!여|\\s*(?:[0-9A-Za-z]|${CURRENCY}|${COUNTER}))`,
    'g',
  )
  return s.replace(re, '$1원')
}
